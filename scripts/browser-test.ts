import 'dotenv/config';
import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:5173';
assert.ok(process.env.SUPABASE_SERVICE_ROLE_KEY, 'Server environment is required for test cleanup');
const browser = await chromium.launch({ headless: true, channel: 'chromium' });
const context = await browser.newContext();
const page = await context.newPage();
const errors: string[] = [];
page.on('pageerror', error => errors.push(error.message));
let createdId: string | undefined;
const paginationIds: string[] = [];
try {
  assert.deepEqual(await context.cookies(), [], 'Start with a fresh browser and no cookies');
  const publicResponse = await context.request.get(`${base}/api/sales`);
  assert.equal(publicResponse.status(), 200, 'Public visitors must be able to load sales');
  await page.goto(base);
  await expect(page.getByRole('heading', { level: 1, name: 'Daily Sales Log', exact: true })).toBeVisible();
  await expect(page.locator('.total')).not.toHaveText('—');
  assert.equal(new URL(page.url()).hash, '', 'No special access link is required');
  const before = await (await context.request.get(`${base}/api/sales`)).json();
  await expect(page.locator('tbody tr')).toHaveCount(Math.min(before.count, 5));
  if (before.count === 0) await expect(page.getByText('No sales recorded yet')).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Sales history', exact: true })).toBeVisible();
  await expect(page.getByRole('columnheader', { name: 'Date', exact: true })).toBeVisible();
  await expect(page.getByLabel('Item name')).toHaveCount(0);
  await expect(page.locator('header, footer, img')).toHaveCount(0);
  await expect(page.getByText('Record a sale. Keep today’s business in view.')).toHaveCount(0);
  await page.getByRole('link', { name: 'Record sale', exact: true }).click();
  await expect(page).toHaveURL(`${base}/record`);
  await expect(page.getByRole('heading', { level: 1, name: 'Daily Sales Log', exact: true })).toBeVisible();
  await expect(page.locator('table')).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Record sale', exact: true })).toBeEnabled();
  const lagosDay = (iso: string) => new Intl.DateTimeFormat('en-CA', { timeZone: 'Africa/Lagos' }).format(new Date(iso));
  const todaysSales = before.sales.filter((sale: { sold_at: string }) => lagosDay(sale.sold_at) === before.day);
  assert.equal(before.today_count, todaysSales.length);
  assert.equal(before.total_kobo, todaysSales.reduce((sum: number, sale: { amount_kobo: number }) => sum + sale.amount_kobo, 0));
  await page.getByRole('button', { name: 'Record sale' }).click();
  await expect(page.getByRole('alert')).toHaveText('Enter an item name.');
  await page.getByLabel('Item name').fill('QA persistence check');
  await page.getByLabel('Sale amount').fill('0');
  await page.getByRole('button', { name: 'Record sale' }).click();
  await expect(page.getByRole('alert')).toContainText('greater than zero');
  const bad = await context.request.post(`${base}/api/sales`, { headers: { Origin: base }, data: { item: 'Invalid', amount: '-1', requestId: crypto.randomUUID() } });
  assert.equal(bad.status(), 400, 'Server must reject invalid amounts');
  const crossOrigin = await context.request.post(`${base}/api/sales`, { headers: { Origin: 'https://example.com' }, data: {} });
  assert.equal(crossOrigin.status(), 403, 'Server must reject cross-origin writes');
  const amountInput = page.getByLabel('Sale amount');
  await amountInput.fill('');
  await amountInput.pressSequentially('1,a.2-e+3/4 ');
  await expect(amountInput).toHaveValue('1234');
  const pasteAllowed = await amountInput.evaluate(el => {
    const data = new DataTransfer(); data.setData('text', '12,345');
    return el.dispatchEvent(new ClipboardEvent('paste', { clipboardData: data, bubbles: true, cancelable: true }));
  });
  assert.equal(pasteAllowed, false, 'Pasting punctuation must be blocked');
  await expect(amountInput).toHaveValue('1234');
  await amountInput.fill('99.50');
  await expect(amountInput).toHaveValue('1234');
  await amountInput.press('Backspace');
  await expect(amountInput).toHaveValue('123');
  await amountInput.fill('1234');
  const savedResponse = page.waitForResponse(response => response.url().endsWith('/api/sales') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Record sale' }).click();
  const saved = await savedResponse;
  assert.equal(saved.status(), 201);
  const sale = await saved.json();
  createdId = sale.id;
  await expect(page.getByRole('dialog', { name: 'Submitted successfully' })).toBeVisible();
  await expect(page.getByLabel('Item name')).toHaveValue('');
  await expect(page.getByLabel('Sale amount')).toHaveValue('');
  await expect.poll(() => page.locator('.success-check path').evaluate(el => getComputedStyle(el).strokeDashoffset)).toBe('0px');
  await mkdir('test-results', { recursive: true });
  await page.screenshot({ path: 'test-results/success-popup.png', fullPage: true });
  await page.getByRole('button', { name: 'Add another sale' }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(page.getByLabel('Item name')).toBeFocused();
  await page.getByRole('link', { name: 'Dashboard', exact: true }).click();
  await expect(page).toHaveURL(`${base}/dashboard`);
  await expect(page.locator('tbody tr').first()).toContainText('QA persistence check');
  const after = await (await context.request.get(`${base}/api/sales`)).json();
  assert.equal(after.total_kobo, before.total_kobo + 123400);
  assert.equal(after.count, before.count + 1);
  assert.equal(after.today_count, before.today_count + 1);
  for (const sale of before.sales) assert.ok(after.sales.some((record: { id: string }) => record.id === sale.id), 'Existing history must remain visible');
  const requestId = saved.request().postDataJSON().requestId;
  const retry = await context.request.post(`${base}/api/sales`, { headers: { Origin: base }, data: { item: 'QA persistence check', amount: '1234', requestId } });
  assert.equal(retry.status(), 201);
  assert.equal((await retry.json()).id, createdId, 'Retry should return the same sale');
  assert.equal((await (await context.request.get(`${base}/api/sales`)).json()).count, after.count);
  await page.reload();
  await expect(page.locator('tbody tr').first()).toContainText('QA persistence check');
  assert.equal((await (await context.request.get(`${base}/api/sales`)).json()).total_kobo, after.total_kobo);
  const dbRecord = await fetch(`${process.env.SUPABASE_URL}/rest/v1/daily_sales?id=eq.${createdId}&select=id,amount_kobo,sold_at`, { headers: { apikey: process.env.SUPABASE_SERVICE_ROLE_KEY!, Authorization: `Bearer ${process.env.SUPABASE_SERVICE_ROLE_KEY}` } });
  assert.equal(dbRecord.status, 200);
  const dbRows = await dbRecord.json();
  assert.equal(dbRows.length, 1);
  assert.equal(dbRows[0].amount_kobo, 123400);
  assert.equal(new Intl.DateTimeFormat('en-CA', { timeZone: 'Africa/Lagos' }).format(new Date(dbRows[0].sold_at)), after.day);
  for (let i = 1; i <= 11; i++) {
    const response = await context.request.post(`${base}/api/sales`, { headers: { Origin: base }, data: { item: `QA pagination ${i}`, amount: String(i), requestId: crypto.randomUUID() } });
    assert.equal(response.status(), 201);
    paginationIds.push((await response.json()).id);
  }
  await page.reload();
  const all = await (await context.request.get(`${base}/api/sales`)).json();
  assert.equal(all.total_kobo, after.total_kobo + 6600);
  await expect(page.locator('tbody tr')).toHaveCount(5);
  const total = await page.locator('.total').textContent();
  const names = (start: number, end: number) => all.sales.slice(start, end).map((sale: { item: string }) => sale.item);
  await expect(page.locator('tbody tr td:first-child')).toHaveText(names(0, 5));
  await expect(page.getByRole('button', { name: 'Previous', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Next', exact: true }).click();
  await expect(page.locator('tbody tr td:first-child')).toHaveText(names(5, 10));
  await expect(page.locator('.total')).toHaveText(total!);
  await page.getByRole('button', { name: 'Next', exact: true }).click();
  await expect(page.locator('tbody tr td:first-child')).toHaveText(names(10, 15));
  const lastPage = Math.ceil(all.count / 5);
  for (let current = 3; current < lastPage; current++) await page.getByRole('button', { name: 'Next', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Next', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Previous', exact: true }).click();
  await expect(page.locator('.page-controls')).toContainText(`Page ${lastPage - 1} of ${lastPage}`);
  await page.setViewportSize({ width: 1280, height: 1000 });
  await mkdir('test-results', { recursive: true });
  await page.screenshot({ path: 'test-results/desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile page must not overflow');
  await page.screenshot({ path: 'test-results/mobile.png', fullPage: true });
  assert.deepEqual(errors, [], 'No browser runtime errors');
  await page.getByRole('link', { name: 'Record sale', exact: true }).click();
  await expect(page.getByLabel('Item name')).toBeVisible();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile sale page must not overflow');
  await page.screenshot({ path: 'test-results/mobile-record.png', fullPage: true });
  assert.deepEqual(await context.cookies(), [], 'Sale creation and refresh must work without authentication cookies');
  console.log(`PASS ${base}: public access without cookies or special links, sale creation, persistence, digits-only input, pagination, complete daily total, success popup, validation, mobile layout.`);
} catch (error) {
  console.error(String(error));
  process.exitCode = 1;
} finally {
  for (const id of paginationIds) {
    const result = await fetch(`${process.env.SUPABASE_URL}/rest/v1/daily_sales?id=eq.${id}`, { method: 'DELETE', headers: { apikey: process.env.SUPABASE_SERVICE_ROLE_KEY!, Authorization: `Bearer ${process.env.SUPABASE_SERVICE_ROLE_KEY}` } });
    assert.ok(result.ok, 'Pagination test record cleanup must succeed');
  }
  if (createdId) {
    const result = await fetch(`${process.env.SUPABASE_URL}/rest/v1/daily_sales?id=eq.${createdId}`, { method: 'DELETE', headers: { apikey: process.env.SUPABASE_SERVICE_ROLE_KEY!, Authorization: `Bearer ${process.env.SUPABASE_SERVICE_ROLE_KEY}` } });
    assert.ok(result.ok, 'Test record cleanup must succeed');
  }
  await browser.close();
}
